import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Regenerates src/contracts/abis.ts from Foundry's out/ artifacts.
 * Run `npm run generate:abis` after `forge build` at the repo root.
 */
const webRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const forgeOut = join(webRoot, "..", "out");

function loadAbi(solFile, contractName) {
  const artifactPath = join(forgeOut, `${solFile}.sol`, `${contractName}.json`);
  const artifact = JSON.parse(readFileSync(artifactPath, "utf8"));
  return artifact.abi;
}

const chogShieldAbi = loadAbi("ChogShield", "ChogShield");
const predictionMarketAbi = loadAbi("PredictionMarket", "PredictionMarket");
const iChogNftAbi = loadAbi("IChogNFT", "IChogNFT");

const generated = `// AUTO-GENERATED by scripts/generate-abis.mjs from Foundry out/ — do not edit by hand.
// Regenerate with \`npm run generate:abis\` after \`forge build\`.

export const chogShieldAbi = ${JSON.stringify(chogShieldAbi, null, 2)} as const;

export const predictionMarketAbi = ${JSON.stringify(predictionMarketAbi, null, 2)} as const;

export const iChogNftAbi = ${JSON.stringify(iChogNftAbi, null, 2)} as const;
`;

const outFile = join(webRoot, "src", "contracts", "abis.ts");
mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, generated);
console.log(`wrote ${outFile}`);
